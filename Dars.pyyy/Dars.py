import turtle
import math

# Ekranni sozlash
screen = turtle.Screen()
screen.title("Uchiha Sharingan")
screen.bgcolor("#111111")
screen.setup(width=600, height=600)

t = turtle.Turtle()
t.speed(0)

# 1. Tashqi qizil doira
t.penup()
t.goto(0, -180)
t.pendown()
t.begin_fill()
t.fillcolor("#e60000")
t.pencolor("black")
t.pensize(6)
t.circle(180)
t.end_fill()

# 2. Ichki qora halqa
t.penup()
t.goto(0, -110)
t.pendown()
t.pensize(4)
t.circle(110)

# 3. Markaziy qora qorachiq
t.penup()
t.goto(0, -30)
t.pendown()
t.begin_fill()
t.fillcolor("black")
t.circle(30)
t.end_fill()

# 4. 3 ta Tomoe (vergul simvollari) chizish
def draw_tomoe(x, y, angle):
    t.penup()
    t.goto(x, y)
    t.setheading(angle)
    t.pendown()
    t.begin_fill()
    t.fillcolor("black")
    t.circle(22)
    t.end_fill()
    
    # Tomoe dum qismi
    t.penup()
    t.goto(x, y)
    t.setheading(angle + 90)
    t.pendown()
    t.begin_fill()
    t.fillcolor("black")
    t.circle(22, 180)
    t.circle(44, 45)
    t.circle(-20, 90)
    t.end_fill()

# Tomoelarni 120 daraja burchak ostida joylashtirish
radius = 110
for i in range(3):
    ang_rad = math.radians(i * 120 + 90)
    tx = radius * math.cos(ang_rad)
    ty = radius * math.sin(ang_rad)
    draw_tomoe(tx, ty, i * 120 + 30)

t.hideturtle()
turtle.done()












